// 小程序原生导航栏标题是静态的（pages.json），切换语言后要手动改一次。
// 用法：在页面 setup 里 setNavTitle(() => tt('gameTitle'))
export function setNavTitle(getTitle) {
  const apply = () => {
    const title = typeof getTitle === 'function' ? getTitle() : getTitle;
    if (title) uni.setNavigationBarTitle({ title });
  };
  watchEffect(apply);
  onMounted(apply);
}
